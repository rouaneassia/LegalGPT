<?php

namespace App\Services;

class StopWordsService
{
    protected array $words = [

        // أدوات الاستفهام
        'ما',
        'ماذا',
        'من',
        'منذ',
        'متى',
        'أين',
        'كيف',
        'كم',
        'هل',
        'لماذا',
        'أي',

        // حروف الجر
        'في',
        'على',
        'عن',
        'إلى',
        'الى',
        'مع',
        'بين',
        'حتى',
        'قبل',
        'بعد',
        'عند',
        'لدى',
        'حول',
        'تحت',
        'فوق',

        // أدوات الربط
        'و',
        'أو',
        'ثم',
        'بل',
        'لكن',
        'إذا',
        'اذا',
        'إن',
        'ان',
        'أن',
        'او',

        // كلمات عامة
        'هو',
        'هي',
        'هم',
        'هن',
        'كان',
        'كانت',
        'يكون',
        'تكون',
        'هناك',
        'هذا',
        'هذه',
        'ذلك',
        'تلك',
        'كل',
        'بعض',
        'جميع',

    ];

    public function remove(array $words): array
    {
        return array_values(
            array_filter(
                $words,
                fn ($word) => ! in_array($word, $this->words)
            )
        );
    }
}