<?php

namespace App\Services;

class ChunkService
{
    /**
     * تقسيم النص إلى Chunks حسب المواد القانونية.
     */
    public function split(string $text): array
    {
        // تنظيف أولي
        $text = str_replace(["\r", "\f"], "\n", $text);

        $text = preg_replace(
            '/[\x{200E}\x{200F}\x{202A}-\x{202E}\x{2066}-\x{2069}]/u',
            '',
            $text
        );

        $text = trim($text);

        if ($text === '') {
            return [];
        }

        /*
        |--------------------------------------------------------------------------
        | تقسيم عند بداية كل مادة
        |--------------------------------------------------------------------------
        */

        $parts = preg_split(
            '/(?=المادة\s+(?:الأولى|الثانية|الثالثة|الرابعة|الخامسة|السادسة|السابعة|الثامنة|التاسعة|العاشرة|[0-9٠-٩]+))/u',
            $text
        );

        $chunks = [];

        foreach ($parts as $part) {

            $part = trim($part);

            if ($part === '') {
                continue;
            }

            $chunks[] = $part;
        }

        /*
        |--------------------------------------------------------------------------
        | إذا لم توجد أي مادة نرجع النص كاملاً
        |--------------------------------------------------------------------------
        */

        if (empty($chunks)) {
            return [$text];
        }

        return $chunks;
    }
}